    private void btnProcesarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcesarActionPerformed
        try {
            //leer los datos de las cajas de texto
            String nombre = txtNombre.getText();
            double saldo = Double.parseDouble(txtSaldo.getText());
            double meta = Double.parseDouble(txtMeta.getText());
            double ahorroDiario = Double.parseDouble(txtAhorro.getText());
            
            //crear el objeto TDA
            alcanciaInteligente miAlcancia = new alcanciaInteligente(nombre, saldo, meta);
           
            //ejecutar la recursividad
            int dias = miAlcancia.calcularDiasFaltantes(miAlcancia.getSaldo(), ahorroDiario);
            
            //imprimir en pantalla
            String texto = "RESULTADOS DE LA ALCANCÍA\n";
            texto += "____________________________________\n";
            texto += "Titular de la cuenta: " + miAlcancia.getTitular() + "\n";
            texto += miAlcancia.revisarProgreso() + "\n";
            texto += "____________________________________\n";
            texto += "\nPROYECCION RECURSIVA \n";
            texto += "Ahorrando $" + ahorroDiario + " diarios...\n";
            texto += "Lograrás tu meta en " + dias + " días.\n";
            texto += "____________________________________\n";
            texto += "Autor: Diego Bautista Tolentino 4B";
            txtResultados.setText(texto);
        } catch (Exception ex) {
            txtResultados.setText("Error, asegúrate de ingresar solo números en Saldo, Meta y Ahorro.");
        }
    }//GEN-LAST:event_btnProcesarActionPerformed

